package cl.duoc.pethome_user_service.enums;

/**
 * Enumeration representing the different user roles in the PetHome system.
 */
public enum UserRole {
    /**
     * Client role - regular users who use the platform
     */
    CLIENT,

    /**
     * Veterinarian role - professionals providing veterinary services
     */
    VET,

    /**
     * Administrator role - system administrators with full privileges
     */
    ADMIN
}
